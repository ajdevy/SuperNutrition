"""Reproduce the frozen USDA package using only Python's standard library.

CLI inputs must match both approved pins. Synthetic unit fixtures call the pure
render helpers directly; there is no production hash-override flag.
"""

import argparse
import hashlib
import json
from pathlib import Path

UPSTREAM_SHA256 = "b80817294b8850530aaedf2e515c02593b1824f763a0ff356e5c2081643e6fd0"
TSV_SHA256 = "1b416249fde1f9a6a0672e71c3ffb216b2a3883f3dbd833a173d3b5332b657eb"
MOBILE = Path(__file__).resolve().parents[3]
SOURCE = MOBILE / "domain/nutrition/src/commonMain/resources/catalog/usda-sr-legacy.tsv"
OUTPUT = Path(__file__).resolve().parents[1] / "src/commonMain/kotlin/com/supernutrition/data/nutrition/BundledUsdaPackage.kt"
PACKAGE = Path(__file__).resolve().parents[1] / "package/usda-sr-legacy-2018-04.tsv"
MANIFEST = Path(__file__).resolve().parents[1] / "package/manifest.json"


def require_pin(data, expected, label):
    actual = hashlib.sha256(data).hexdigest()
    if actual != expected:
        raise ValueError(f"{label} SHA-256 mismatch: expected {expected}, got {actual}")


def package_rows(source):
    rows = []
    identifiers = set()
    for line in source.splitlines():
        if not line.startswith("F\t"):
            continue
        fields = line.split("\t")
        if len(fields) != 10 or fields[1] in identifiers:
            raise ValueError("Malformed or duplicate USDA food row")
        identifiers.add(fields[1])
        rows.append(line[2:])
    if not rows:
        raise ValueError("Empty source inventory")
    return "\n".join(rows) + "\n"


def kotlin_string(value):
    return json.dumps(value, ensure_ascii=True).replace("$", "\\$")


def render_kotlin(body):
    # A constant is bounded below the JVM constant-pool UTF-8 limit. Splitting
    # source literals also keeps generated source lines below 120 columns.
    parts = [body[start:start + 8000] for start in range(0, len(body), 8000)]
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    lines = [
        "package com.supernutrition.data.nutrition", "",
        "// Generated by mobile/data/nutrition/tools/generate_bundled_catalog.py.",
        "// USDA FoodData Central SR Legacy 2018-04; CC0 1.0; values per 100 g edible portion.",
        "// Empty cells are unknown, never zero. Reproduce with the pinned archive and TSV.",
        "internal object BundledUsdaPackage {",
        f'    const val DIGEST = "{digest}"',
        f"    const val FOOD_COUNT = {len(body.splitlines())}",
        "    val payload: String = listOf(",
    ]
    lines.extend(f"        USDA_PART_{index}," for index in range(len(parts)))
    lines += ['    ).joinToString("")', "}", ""]
    for index, part in enumerate(parts):
        fragments = [part[start:start + 64] for start in range(0, len(part), 64)]
        lines.append(f"private const val USDA_PART_{index} =")
        lines.extend(
            ("    " if offset == 0 else "        ") + kotlin_string(fragment) +
            (" +" if offset < len(fragments) - 1 else "")
            for offset, fragment in enumerate(fragments)
        )
        lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream-archive", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="verify checked-in outputs without modifying them")
    args = parser.parse_args()
    require_pin(args.upstream_archive.read_bytes(), UPSTREAM_SHA256, "USDA archive")
    source = SOURCE.read_bytes()
    require_pin(source, TSV_SHA256, "Imported TSV")
    body = package_rows(source.decode("utf-8"))
    manifest = {
        "schema": "supernutrition.usda-bundled-package/v1",
        "nutritionContract": "grounded-nutrition/v2",
        "catalogId": "usda-sr-legacy",
        "release": "2018-04",
        "catalogCountry": "US",
        "foodCount": len(body.splitlines()),
        "packageSha256": hashlib.sha256(body.encode("utf-8")).hexdigest(),
        "sourceTsvSha256": TSV_SHA256,
        "upstreamArchiveSha256": UPSTREAM_SHA256,
        "upstreamUrl": "https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip",
        "licence": "CC0-1.0",
        "licenceUrl": "https://creativecommons.org/publicdomain/zero/1.0/",
        "basis": "per 100 g edible portion; grams entered explicitly",
        "missingValue": "empty cell is unknown; source zero remains zero",
        "activation": "immutable app-bundled payload; no downloaded catalog updates",
        "authentication": "enclosing application's signature; separate payload/source SHA-256 pins",
    }
    outputs = {
        OUTPUT: render_kotlin(body),
        PACKAGE: body,
        MANIFEST: json.dumps(manifest, ensure_ascii=True, indent=2) + "\n",
    }
    for path, expected in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                raise ValueError(f"Generated output differs: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Verified {manifest['foodCount']} foods; package SHA-256 {manifest['packageSha256']}")


if __name__ == "__main__":
    main()
